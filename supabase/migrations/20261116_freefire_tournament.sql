-- Không ghi đè bảng dữ liệu StudyT; các bảng ff_* tách biệt.
BEGIN;

CREATE OR REPLACE FUNCTION public.ff_is_admin() RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, auth AS $$
  SELECT auth.uid() IS NOT NULL
    AND lower(coalesce(auth.jwt() ->> 'email','')) = 'hktrieuvioletvc@gmail.com'
    AND EXISTS (SELECT 1 FROM public.profiles p WHERE p.id = auth.uid() AND p.role = 'admin');
$$;
REVOKE ALL ON FUNCTION public.ff_is_admin() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.ff_is_admin() TO authenticated;

CREATE TABLE IF NOT EXISTS public.ff_accounts (
  user_id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  alias varchar(40) NOT NULL UNIQUE,
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE OR REPLACE FUNCTION public.ff_is_tournament_account() RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, auth AS $$
  SELECT EXISTS (SELECT 1 FROM public.ff_accounts a WHERE a.user_id = auth.uid());
$$;
REVOKE ALL ON FUNCTION public.ff_is_tournament_account() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.ff_is_tournament_account() TO authenticated;

CREATE OR REPLACE FUNCTION public.ff_access_active() RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, auth AS $$
  SELECT NOT public.ff_is_tournament_account()
    OR EXISTS (SELECT 1 FROM public.ff_accounts a WHERE a.user_id = auth.uid() AND a.active);
$$;
REVOKE ALL ON FUNCTION public.ff_access_active() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.ff_access_active() TO authenticated;

CREATE TABLE IF NOT EXISTS public.ff_identities (
  user_id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  student_code varchar(64) NOT NULL CHECK (char_length(btrim(student_code)) BETWEEN 3 AND 64),
  full_name varchar(120) NOT NULL CHECK (char_length(btrim(full_name)) BETWEEN 2 AND 120),
  birth_date date NOT NULL CHECK (birth_date >= DATE '1900-01-01' AND birth_date <= CURRENT_DATE),
  confirmed_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.ff_registrations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES public.ff_identities(user_id) ON DELETE CASCADE,
  mode varchar(16) NOT NULL CHECK (mode IN ('survival','clash','duel')),
  game_uid varchar(32) NOT NULL CHECK (game_uid ~ '^[0-9]{5,20}$'),
  nickname varchar(60) NOT NULL CHECK (char_length(btrim(nickname)) BETWEEN 2 AND 60),
  team_name varchar(60),
  rules_accepted_at timestamptz NOT NULL DEFAULT now(),
  status varchar(16) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected')),
  admin_note text,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (user_id, mode),
  CONSTRAINT ff_clash_team_name CHECK (mode <> 'clash' OR (team_name IS NOT NULL AND char_length(btrim(team_name)) BETWEEN 2 AND 60))
);
CREATE INDEX IF NOT EXISTS ff_reg_user_idx ON public.ff_registrations(user_id, status);
CREATE UNIQUE INDEX IF NOT EXISTS ff_reg_unique_uid_mode ON public.ff_registrations(mode, game_uid) WHERE status <> 'rejected';

CREATE TABLE IF NOT EXISTS public.ff_br_results (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  match_no smallint NOT NULL CHECK (match_no BETWEEN 1 AND 5),
  placement smallint NOT NULL CHECK (placement BETWEEN 1 AND 50),
  kills smallint NOT NULL CHECK (kills BETWEEN 0 AND 49),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (user_id, match_no),
  UNIQUE (match_no, placement)
);
CREATE TABLE IF NOT EXISTS public.ff_clash_matches (
  match_no smallint PRIMARY KEY CHECK (match_no BETWEEN 1 AND 5),
  team_a varchar(60) NOT NULL CHECK (char_length(btrim(team_a)) BETWEEN 2 AND 60),
  team_b varchar(60) NOT NULL CHECK (char_length(btrim(team_b)) BETWEEN 2 AND 60),
  rounds_a smallint NOT NULL CHECK (rounds_a BETWEEN 0 AND 4),
  rounds_b smallint NOT NULL CHECK (rounds_b BETWEEN 0 AND 4),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ff_clash_diff_teams CHECK (lower(btrim(team_a)) <> lower(btrim(team_b))),
  CONSTRAINT ff_clash_valid_win CHECK ((rounds_a = 4 AND rounds_b < 4) OR (rounds_b = 4 AND rounds_a < 4))
);
CREATE TABLE IF NOT EXISTS public.ff_duel_matches (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  stage varchar(32) NOT NULL CHECK (stage IN ('Vòng loại','Tứ kết','Bán kết','Chung kết','Tranh hạng ba')),
  player_a uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  player_b uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  score_a smallint NOT NULL CHECK (score_a BETWEEN 0 AND 5),
  score_b smallint NOT NULL CHECK (score_b BETWEEN 0 AND 5),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ff_duel_diff_players CHECK (player_a <> player_b),
  CONSTRAINT ff_duel_valid_win CHECK ((score_a = 5 AND score_b < 5) OR (score_b = 5 AND score_a < 5))
);
CREATE UNIQUE INDEX IF NOT EXISTS ff_duel_one_final ON public.ff_duel_matches(stage) WHERE stage IN ('Chung kết','Tranh hạng ba');

ALTER TABLE public.ff_accounts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ff_identities ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ff_registrations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ff_br_results ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ff_clash_matches ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ff_duel_matches ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS ff_accounts_read ON public.ff_accounts;
CREATE POLICY ff_accounts_read ON public.ff_accounts FOR SELECT TO authenticated USING (user_id = auth.uid() OR public.ff_is_admin());
DROP POLICY IF EXISTS ff_accounts_admin ON public.ff_accounts;
CREATE POLICY ff_accounts_admin ON public.ff_accounts FOR UPDATE TO authenticated USING (public.ff_is_admin()) WITH CHECK (public.ff_is_admin());

DROP POLICY IF EXISTS ff_id_read ON public.ff_identities;
CREATE POLICY ff_id_read ON public.ff_identities FOR SELECT TO authenticated USING (user_id = auth.uid() OR public.ff_is_admin());
DROP POLICY IF EXISTS ff_id_insert ON public.ff_identities;
CREATE POLICY ff_id_insert ON public.ff_identities FOR INSERT TO authenticated WITH CHECK (user_id = auth.uid());
DROP POLICY IF EXISTS ff_id_update ON public.ff_identities;
CREATE POLICY ff_id_update ON public.ff_identities FOR UPDATE TO authenticated USING (user_id = auth.uid() OR public.ff_is_admin()) WITH CHECK (user_id = auth.uid() OR public.ff_is_admin());

DROP POLICY IF EXISTS ff_reg_read ON public.ff_registrations;
CREATE POLICY ff_reg_read ON public.ff_registrations FOR SELECT TO authenticated USING (user_id = auth.uid() OR public.ff_is_admin());
DROP POLICY IF EXISTS ff_reg_insert ON public.ff_registrations;
CREATE POLICY ff_reg_insert ON public.ff_registrations FOR INSERT TO authenticated WITH CHECK (
  user_id = auth.uid() AND status = 'pending' AND admin_note IS NULL
  AND EXISTS (SELECT 1 FROM public.ff_identities i WHERE i.user_id = auth.uid())
  AND (NOT public.ff_is_tournament_account() OR EXISTS (SELECT 1 FROM public.ff_accounts a WHERE a.user_id = auth.uid() AND a.active))
);
DROP POLICY IF EXISTS ff_reg_admin_update ON public.ff_registrations;
CREATE POLICY ff_reg_admin_update ON public.ff_registrations FOR UPDATE TO authenticated USING (public.ff_is_admin()) WITH CHECK (public.ff_is_admin());

DROP POLICY IF EXISTS ff_br_read ON public.ff_br_results;
CREATE POLICY ff_br_read ON public.ff_br_results FOR SELECT TO authenticated USING (true);
DROP POLICY IF EXISTS ff_br_admin_insert ON public.ff_br_results;
CREATE POLICY ff_br_admin_insert ON public.ff_br_results FOR INSERT TO authenticated WITH CHECK (
  public.ff_is_admin() AND EXISTS (SELECT 1 FROM public.ff_registrations r WHERE r.user_id = ff_br_results.user_id AND r.mode = 'survival' AND r.status = 'approved')
);
DROP POLICY IF EXISTS ff_br_admin_update ON public.ff_br_results;
CREATE POLICY ff_br_admin_update ON public.ff_br_results FOR UPDATE TO authenticated USING (public.ff_is_admin()) WITH CHECK (public.ff_is_admin());
DROP POLICY IF EXISTS ff_br_admin_delete ON public.ff_br_results;
CREATE POLICY ff_br_admin_delete ON public.ff_br_results FOR DELETE TO authenticated USING (public.ff_is_admin());

DROP POLICY IF EXISTS ff_clash_read ON public.ff_clash_matches;
CREATE POLICY ff_clash_read ON public.ff_clash_matches FOR SELECT TO authenticated USING (true);
DROP POLICY IF EXISTS ff_clash_write ON public.ff_clash_matches;
CREATE POLICY ff_clash_write ON public.ff_clash_matches FOR ALL TO authenticated USING (public.ff_is_admin()) WITH CHECK (
  public.ff_is_admin()
  AND (SELECT count(*) FROM public.ff_registrations r WHERE r.mode='clash' AND r.status='approved' AND lower(btrim(r.team_name))=lower(btrim(team_a))) >= 4
  AND (SELECT count(*) FROM public.ff_registrations r WHERE r.mode='clash' AND r.status='approved' AND lower(btrim(r.team_name))=lower(btrim(team_b))) >= 4
);

DROP POLICY IF EXISTS ff_duel_read ON public.ff_duel_matches;
CREATE POLICY ff_duel_read ON public.ff_duel_matches FOR SELECT TO authenticated USING (true);
DROP POLICY IF EXISTS ff_duel_write ON public.ff_duel_matches;
CREATE POLICY ff_duel_write ON public.ff_duel_matches FOR ALL TO authenticated USING (public.ff_is_admin()) WITH CHECK (
  public.ff_is_admin()
  AND EXISTS (SELECT 1 FROM public.ff_registrations r WHERE r.user_id = player_a AND r.mode = 'duel' AND r.status='approved')
  AND EXISTS (SELECT 1 FROM public.ff_registrations r WHERE r.user_id = player_b AND r.mode = 'duel' AND r.status='approved')
);

-- Bảng công khai không tiết lộ ID học sinh, ngày sinh, UID game hay ghi chú quản trị.
CREATE OR REPLACE VIEW public.ff_public_players WITH (security_barrier = true) AS
  SELECT r.user_id, r.mode, r.nickname, r.team_name
  FROM public.ff_registrations r
  WHERE r.status = 'approved';
REVOKE ALL ON public.ff_public_players FROM PUBLIC, anon;
GRANT SELECT ON public.ff_public_players TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.ff_accounts, public.ff_identities, public.ff_registrations, public.ff_br_results, public.ff_clash_matches, public.ff_duel_matches TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.ff_registrations_id_seq, public.ff_br_results_id_seq, public.ff_duel_matches_id_seq TO authenticated;

-- Tạm khóa có hiệu lực trên dữ liệu giải đấu ngay cả khi phiên đăng nhập còn tồn tại.
DO $$DECLARE t text; BEGIN
  FOREACH t IN ARRAY ARRAY['ff_identities','ff_registrations','ff_br_results','ff_clash_matches','ff_duel_matches'] LOOP
    EXECUTE format('DROP POLICY IF EXISTS ff_active_only ON public.%I', t);
    EXECUTE format('CREATE POLICY ff_active_only ON public.%I AS RESTRICTIVE FOR ALL TO authenticated USING (public.ff_access_active()) WITH CHECK (public.ff_access_active())', t);
  END LOOP;
END $$;

-- Cô lập 15 tài khoản khỏi dữ liệu các module hiện có bằng restrictive RLS.
-- Chỉ áp dụng trên bảng đã bật RLS; không tự sửa dữ liệu hoặc policy sẵn có.
DO $$DECLARE t record; p text; BEGIN
  FOR t IN SELECT c.relname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname='public' AND c.relkind='r' AND c.relrowsecurity
      AND c.relname NOT LIKE 'ff\_%' ESCAPE '\' AND c.relname <> 'profiles'
  LOOP
    p := 'ff_deny_tournament_' || substr(md5(t.relname),1,12);
    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I',p,t.relname);
    EXECUTE format('CREATE POLICY %I ON public.%I AS RESTRICTIVE FOR ALL TO authenticated USING (NOT public.ff_is_tournament_account()) WITH CHECK (NOT public.ff_is_tournament_account())',p,t.relname);
  END LOOP;
END $$;
-- Riêng profiles: tài khoản giải đấu chỉ xem/sửa hồ sơ của chính họ.
DO $$ BEGIN
  IF EXISTS (SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace WHERE n.nspname='public' AND c.relname='profiles' AND c.relrowsecurity) THEN
    DROP POLICY IF EXISTS ff_profiles_isolate ON public.profiles;
    CREATE POLICY ff_profiles_isolate ON public.profiles AS RESTRICTIVE FOR ALL TO authenticated
      USING (NOT public.ff_is_tournament_account() OR id = auth.uid())
      WITH CHECK (NOT public.ff_is_tournament_account() OR id = auth.uid());
  END IF;
END $$;
COMMIT;

